/* ==========================================================================
   Sonora · «кто сейчас на сайте»
   Cloudflare Worker + Durable Object.

   Зачем это вообще нужно. На статике знать, сколько людей открыли страницу
   прямо сейчас, невозможно: у каждого посетителя своя копия страницы, и его
   браузер физически не знает, что кто-то ещё где-то открыл тот же адрес. Число
   должно где-то накапливаться — значит, должен быть кто-то, кто его выполняет.
   Этот файл и есть тот кто-то.

   Как считаем. Каждый браузер раз в 30 секунд говорит Worker'у «я здесь» и
   получает в ответ, сколько сессий живых. Сессия — это не человек, а вкладка:
   идентификатор лежит в sessionStorage, поэтому перезагрузка страницы не
   создаёт второго человека, а вторая вкладка создаёт. Сессия считается живой,
   пока её видели меньше 75 секунд назад; всё, что замолчало, вычищается при
   каждом запросе. Отсюда и числа: 30 с пинг, 75 с окно — запас в 2,5 раза, чтобы
   просадка сети не выкидывала человека из подсчёта.

   Хранилище — Durable Object, и не случайно. В Workers KV не хватит: на
   бесплатном тарифе там тысяча записей в сутки, а один человек, пингуя раз в
   30 секунд, пишет почти три тысячи. Здесь же состояние живёт в памяти и
   ничего не пишет вообще — а после перезапуска экземпляра счётчик
   восстанавливается сам за один интервал, как только придёт следующий пинг.
   Считать это можно было и на обычном Worker с записью в файл, но тогда каждая
   запись стоила бы запроса к хранилищу именно ради того, чтобы узнать, что
   заходил кто-то, кто и так уже ушёл.

   Чего тут нет. Никакой валидации, что посетитель пришёл с сайта: адрес и так
   открыт для всех, а закрывать его было бы ложной защитой — тот же приём, что
   и с паролем в админ-панели, только наряднее. И по той же причине счётчик
   ничего не защищает: он показывает красивое число, и его можно накрутить.
   Для витрины этого достаточно.
   ========================================================================== */

/** сколько живёт сессия без пинга */
const ALIVE_MS = 75_000;

/** как часто браузер должен себя показывать — это отдаётся клиенту, чтобы он
    не гадал с интервалом и не пинговал чаще нужного */
const PING_MS = 30_000;

/** предохранитель от накрутки: больше живых сессий в одну секунду не держим */
const MAX_LIVE = 2000;

/**
 * Durable Object: держит множество живых сессий.
 *
 * Состояние — обычная Map прямо в памяти экземпляра. Никакого хранилища: пинг
 * идёт раз в полминуты, и тратить на каждого по операции записи ради счётчика
 * было бы расточительством.
 */
export class Sessions {
  constructor(_state) {
    /** идентификатор сессии → когда её видели в последний раз */
    this.live = new Map();
  }

  async fetch(request) {
    const id = new URL(request.url).searchParams.get('id') || '';

    /* без идентификатора считать нечего: это не заход на сайт, а мусор */
    if (!id || id.length > 64) return json({ error: 'bad id' }, 400);

    const now = Date.now();

    /* чистим всё, что замолчало. Проход по всей карте на каждый запрос — это
       нормально только потому, что карта живёт 75 секунд и потому, что весь
       смысл этого Worker'а в том, чтобы сойтись в одну точку. */
    for (const [key, seen] of this.live) {
      if (now - seen > ALIVE_MS) this.live.delete(key);
    }

    if (this.live.size >= MAX_LIVE) {
      /* упёрлись — не добавляем новых, но честно отдаём текущую картину */
      return json({ online: this.live.size, ping: PING_MS, capped: true });
    }

    this.live.set(id, now);
    return json({ online: this.live.size, ping: PING_MS });
  }
}

/**
 * Наружу отдаём счётчик, внутри — Sessions.
 *
 * Экземпляр Durable Object ровно один, на всех: `idFromName` с постоянным
 * именем. Это и есть причина, по которой здесь нужен Durable Object, а не
 * обычный Worker — и одновременно ошибка, которую легко сделать: если дать
 * каждому посетителю свой экземпляр по его идентификатору, то каждый посетитель
 * увидит ровно одного человека. Себя.
 */
export default {
  async fetch(request, env) {
    if (request.method === 'OPTIONS') {
      return new Response(null, { status: 204, headers: CORS });
    }
    if (request.method !== 'GET') {
      return withCors(json({ error: 'method not allowed' }, 405));
    }

    /* привязка не настроена — отвечаем честным нулём, а не падением */
    if (!env.SESSIONS) {
      return withCors(json({ online: 0, ping: PING_MS, ready: false }));
    }

    const hub = env.SESSIONS.get(env.SESSIONS.idFromName('sonora'));
    return withCors(await hub.fetch(request));
  },
};

/* Сайт живёт на maksim8560.github.io, Worker — на *.workers.dev, то есть это
   разные источники, и без этого заголовка браузер не отдаст ответ странице.
   Открывать ответ всем можно: он ничего не сообщает, кроме числа, и ничего не
   меняет. */
const CORS = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Methods': 'GET, OPTIONS',
  'Access-Control-Max-Age': '86400',
};

function withCors(res) {
  const headers = new Headers(res.headers);
  for (const [key, value] of Object.entries(CORS)) headers.set(key, value);
  return new Response(res.body, { status: res.status, headers });
}

function json(data, status = 200) {
  return new Response(JSON.stringify(data), {
    status,
    headers: { 'content-type': 'application/json; charset=utf-8' },
  });
}
